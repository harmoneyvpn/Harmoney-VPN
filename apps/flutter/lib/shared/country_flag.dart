class CountryFlag extends StatelessWidget {
  const CountryFlag({super.key, required this.code, this.size = 34});
  final String code;
  final double size;

  @override
  Widget build(BuildContext context) {
    final normalized = CountryFlags.normalize(code);
    final fallback = Center(
      child: LocalizedText(
        CountryFlags.emoji(normalized),
        style: TextStyle(
          fontFamily: 'NotoColorEmoji',
          fontSize: size * 0.78,
          height: 1,
        ),
      ),
    );
    return SizedBox(
      width: size,
      height: size,
      child: CountryFlags.hasSvg(normalized)
          ? ClipOval(
              child: SvgPicture.asset(
                'assets/flags/${normalized.toLowerCase()}.svg',
                fit: BoxFit.cover,
                errorBuilder: (context, error, stackTrace) => fallback,
              ),
            )
          : fallback,
    );
  }
}
