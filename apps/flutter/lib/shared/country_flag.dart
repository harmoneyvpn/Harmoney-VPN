  static String normalize(String? value) {
    final code = value?.trim().toUpperCase();
    if (code == 'UK') return 'GB';
    if (code == 'XK') return 'XK';
    return _countries.contains(code) ? code! : '';
  }

  static String resolve(VpnServer? server) {
    if (server == null) return '';
    // Harmoney CF means Cloudflare, not the Central African Republic.
    if (server.providerId == 'harmoney' &&
        [
          'AUTO',
          'CF',
          'UNKNOWN',
        ].contains(server.countryCode?.trim().toUpperCase())) {
      return '';
    }
    final explicit = normalize(server.countryCode);
    if (explicit.isNotEmpty) return explicit;
    final prefix = normalize(server.id.split(RegExp('[-_:]')).first);
    if (prefix.isNotEmpty) return prefix;
    return normalize(_names[server.country.trim().toLowerCase()]);
  }

  static String emoji(String? value) {
    final code = normalize(value);
    if (code.isEmpty) return '🌐';
    return String.fromCharCodes(code.codeUnits.map((c) => c + 0x1f1e6 - 65));
  }

